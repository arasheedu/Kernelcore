#!/bin/bash
# gen_matmul_kq8k.sh <q4|q6> <T>: prints matmul_<q>k_q8kx<T>.cu, the K-quant matmul for activations
# quantized per 256 values (quantize_cols_k.cu), T columns per thread. The kernels in kernels/llm/
# come from
#   for q in q4 q6; do for t in 4 8; do bash scripts/gen_matmul_kq8k.sh $q $t > kernels/llm/matmul_${q}k_q8kx$t.cu; done; done
set -e
q=$1; T=$2
[ "$q" = q4 ] || [ "$q" = q6 ] || { echo "usage: $0 <q4|q6> <T>" >&2; exit 2; }
here=$(cd "$(dirname "$0")/.." && pwd)
rep() { local s="$1"; for ((i=0;i<T;i++)); do echo "${s//@/$i}"; done; }
if [ $q = q4 ]; then Q=Q4_K; words=37; else Q=Q6_K; words=53; fi

cat <<E
// Generated by scripts/gen_matmul_kq8k.sh $q $T. Do not edit.
// Y = W X for GGUF $Q weights and several 8-bit activation columns quantized per 256 values (one
// scale per super-block, as llama.cpp's Q8_K): each thread computes one row for a tile of $T columns.
// The integer dot products of a whole super-block are summed as integers (with the weight scales,
// and the activation sums for the $(if [ $q = q4 ]; then echo "mins"; else echo "-32 offset"; fi)), then scaled once per super-block, so there is
// one float step per 256 values instead of per 32.
// xq: one slot per column of nsb = k / 256 super-blocks, [nsb * 64 words | nsb floats (scale) |
// nsb * 16 ints (sums of 16 values) | nsb * 4 words (sums of 32 as bytes)], column c at
// xq + c * nsb * 85 (quantize_cols_k.cu).
// Weights: $words words x 8 rows per super-block, as matvec_${q}k_q8.cu. y: column c at y + c * rows.
// Threads, tiles, dims {rows, k, ncols, rb} and base as in matmul_q4k_q8x4.cu.

E
# the dp4a and aligned8 helpers, from the 4-column kernel
sed -n '/^#ifndef KC_DP4A_DEFINED/,/^extern "C"/p' "$here/kernels/llm/matmul_q4k_q8x4.cu" | sed '$d'
echo "extern \"C\" __global__ void matmul_${q}k_q8kx${T}(const int* qw, const int* xq, float* y, const int* dims, int base)"
cat <<E
{
    const int idx = kc_aligned8(base) + blockIdx.x * blockDim.x + threadIdx.x;
    const int rows = kc_aligned8(dims[0]);
    const int k = dims[1];
    const int ncols = dims[2];
    const int rb = dims[3];
    const int tiles = (ncols + $((T-1))) / $T;
    if (idx < rows * tiles) {
        // Blocks of rb 8-row groups, each run for tile 0, then tile 1, ... (matmul_q4k_q8x4.cu).
        const int ng = rows / 8;
        const int grp = idx / 8;
        const int blk = grp / (rb * tiles);
        const int g0 = blk * rb;
        int rbn;
        if (ng - g0 < rb) rbn = ng - g0;
        else rbn = rb;
        const int within = grp - g0 * tiles;
        const int tile = within / rbn;
        const int g = g0 + within - tile * rbn;
        const int l = idx - grp * 8;
        const int row = g * 8 + l;
        const int nsb = k / 256;
        const int c0 = tile * $T;
E
for ((i=1;i<T;i++)); do echo "        int c$i;"; echo "        if (c0 + $i < ncols) c$i = c0 + $i;"; echo "        else c$i = c$((i-1));"; done
rep '        const int * x@ = xq + c@ * nsb * 85;'
rep '        const float * xd@ = (const float *)(x@ + nsb * 64);'
rep '        const int * bs@ = x@ + nsb * 65;'
rep '        float acc@ = 0.0f;'
if [ $q = q4 ]; then
cat <<'E'
        for (int s = 0; s < nsb; ++s) {
            const int wb = (g * nsb + s) * 296;  // 37 words x 8 rows
            const float d = ((const float*)qw)[wb + l];
            const float dmin = ((const float*)qw)[wb + 8 + l];
            const int s0 = qw[wb + 16 + l];
            const int s1 = qw[wb + 24 + l];
            const int s2 = qw[wb + 32 + l];
            const int sclo = s0 & 1061109567;                                      // 0x3F3F3F3F
            const int mlo = s1 & 1061109567;
            const int schi = (s2 & 252645135) | ((s0 >> 2) & 808464432);          // 0x0F0F0F0F, 0x30303030
            const int mhi = ((s2 >> 4) & 252645135) | ((s1 >> 2) & 808464432);
E
rep '            int is@ = 0;'
cat <<'E'
            for (int j = 0; j < 4; ++j) {
                const int b = s * 8 + j * 2;
                const int sh = 16 * (j & 1);
                int scw;
                if (j < 2) scw = sclo;
                else scw = schi;
                const int sca = (scw >> sh) & 255;
                const int scb = (scw >> (sh + 8)) & 255;
                // Low nibbles (sub-block 2j), then high nibbles (2j + 1): T accumulators per loop, so
                // they stay in registers.
E
rep '                int da@ = 0;'
cat <<'E'
                for (int w = 0; w < 8; ++w) {
                    const int lo = qw[wb + (5 + j * 8 + w) * 8 + l] & 252645135;
E
for ((i=0;i<T;i++)); do echo "                    da$i = kc_dp4a(lo, x$i[b * 8 + w], da$i);"; done
echo "                }"
rep '                is@ += sca * da@;'
rep '                int db@ = 0;'
cat <<'E'
                for (int w = 0; w < 8; ++w) {
                    const int hi = (qw[wb + (5 + j * 8 + w) * 8 + l] >> 4) & 252645135;
E
for ((i=0;i<T;i++)); do echo "                    db$i = kc_dp4a(hi, x$i[b * 8 + 8 + w], db$i);"; done
echo "                }"
rep '                is@ += scb * db@;'
echo "            }"
cat <<'E'
            // Mins: sum over the 8 sub-blocks of min * B, B the sum of the sub-block's 32 activations,
            // as dot products of the packed mins (mlo: sub-blocks 0-3, mhi: 4-7) with B's bytes
            // (B >> 6, then B & 63; quantize_cols_k.cu).
E
rep '            const int * pm@ = x@ + nsb * 81 + s * 4;'
rep '            const int im@ = 64 * (kc_dp4a(mlo, pm@[0], 0) + kc_dp4a(mhi, pm@[1], 0)) + kc_dp4a(mlo, pm@[2], 0) + kc_dp4a(mhi, pm@[3], 0);'
rep '            acc@ += (d * xd@[s]) * (float)is@ - (dmin * xd@[s]) * (float)im@;'
echo "        }"
else
cat <<'E'
        for (int s = 0; s < nsb; ++s) {
            const int wb = (g * nsb + s) * 424;  // 53 words x 8 rows
            const float d = ((const float*)qw)[wb + 52 * 8 + l];
E
rep '            int is@ = 0;'
cat <<'E'
            for (int n = 0; n < 2; ++n) {
                for (int t = 0; t < 4; ++t) {
                    const int b = s * 8 + n * 4 + t;
                    const int o = s * 16 + (n * 4 + t) * 2;  // the two sums of 16 of this block of 32
                    const int qlw = 16 * n + 8 * (t & 1);
                    const int lowsh = 4 * (t >> 1);
                    const int hish = 2 * t;
                    const int scw = qw[wb + (48 + 2 * n + (t >> 1)) * 8 + l];
                    const int sh = 16 * (t & 1);
                    const int sca = (scw << (24 - sh)) >> 24;
                    const int scb = (scw << (16 - sh)) >> 24;
E
rep '                    int da@ = 0;'
rep '                    int db@ = 0;'
cat <<'E'
                    for (int w = 0; w < 4; ++w) {
                        const int lo = (qw[wb + (qlw + w) * 8 + l] >> lowsh) & 252645135;                  // 0x0F0F0F0F
                        const int hi = ((qw[wb + (32 + 8 * n + w) * 8 + l] >> hish) << 4) & 808464432;    // 0x30303030
                        const int q = lo | hi;
E
rep '                        da@ = kc_dp4a(q, x@[b * 8 + w], da@);'
cat <<'E'
                    }
                    for (int w = 4; w < 8; ++w) {
                        const int lo = (qw[wb + (qlw + w) * 8 + l] >> lowsh) & 252645135;
                        const int hi = ((qw[wb + (32 + 8 * n + w) * 8 + l] >> hish) << 4) & 808464432;
                        const int q = lo | hi;
E
rep '                        db@ = kc_dp4a(q, x@[b * 8 + w], db@);'
echo "                    }"
echo "                    // weights are q - 32: subtract 32 x the activation sums"
rep '                    is@ += sca * (da@ - 32 * bs@[o]) + scb * (db@ - 32 * bs@[o + 1]);'
echo "                }"
echo "            }"
rep '            acc@ += (d * xd@[s]) * (float)is@;'
echo "        }"
fi
echo "        y[c0 * rows + row] = acc0;"
for ((i=1;i<T;i++)); do echo "        if (c0 + $i < ncols) y[(c0 + $i) * rows + row] = acc$i;"; done
echo "    }"
echo "}"
